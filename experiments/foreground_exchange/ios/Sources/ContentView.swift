import SwiftUI

struct ContentView: View {
    @Environment(\.scenePhase) private var scenePhase
    @EnvironmentObject private var model: ProbeModel
    @State private var payloadSize = 2048
    private let payloadSizes = [256, 2048, 8192]

    var body: some View {
        NavigationStack {
            Form {
                Section {
                    Text("Test-only transport session").font(.title2.weight(.semibold))
                    Text("Start on both phones. Each compatible peer sends 20 attempts and receives the other phone's test bytes automatically. Generated bytes only; do not send reports, messages, or private data.")
                }
                Section("Session") {
                    Picker("Payload size", selection: $payloadSize) {
                        ForEach(payloadSizes, id: \.self) { size in
                            Text(size == 256 ? "256 bytes" : size == 2048 ? "2 KiB (required gate)" : "8 KiB").tag(size)
                        }
                    }.disabled(model.sessionActive && !model.awaitingResume)
                    Text("Use the same payload size on both phones. iPhone finds Android over Bluetooth. iPhone-to-iPhone has not been validated and is unsupported by this probe.")
                        .font(.footnote).foregroundStyle(.secondary)
                    Button(model.awaitingResume ? "Start a new test session" : "Start test session") {
                        model.start(payloadSize: payloadSize)
                    }.disabled(model.sessionActive && !model.awaitingResume)
                    if model.awaitingResume {
                        Button("Resume saved session") {
                            payloadSize = model.selectedPayloadSize
                            model.resume()
                        }
                    }
                    Button("Stop session", role: .destructive) { model.stop() }.disabled(!model.sessionActive)
                }
                Section("Status") {
                    Text(model.status)
                    Text("Sent: \(model.successfulAttempts) successful · \(model.failedAttempts) failed").monospacedDigit()
                    Text("Received: \(model.receivedAttempts) unique · \(model.duplicateAttempts) duplicates").monospacedDigit()
                    Text("\(model.completedPeers) peer batches completed").monospacedDigit()
                }
                Section("While the app is away") {
                    Text(model.backgroundPolicy).font(.footnote)
                    Text("On iOS 26, a local Live Activity can improve background Bluetooth availability. Discovery may stop when the screen turns fully off. Your session progress is saved and resumes automatically when TrailMesh becomes active. Reopening an interrupted app offers Resume.")
                        .font(.footnote).foregroundStyle(.secondary)
                    if #available(iOS 26.0, *), model.sessionActive && !model.awaitingResume {
                        Button("Show session Live Activity") { model.enableBackgroundActivity() }
                    }
                }
                Section("Redacted test log") {
                    if model.logs.isEmpty {
                        Text("No attempts recorded yet.").foregroundStyle(.secondary)
                    } else {
                        ForEach(Array(model.logs.suffix(100).enumerated()), id: \.offset) { item in
                            Text(item.element).font(.caption.monospaced())
                        }
                    }
                    ShareLink("Export redacted log", item: model.exportJSON)
                }
                Section {
                    Label("Automatic verification is test-only. Session identifiers prevent stale transfers; they do not authenticate a peer. The probe carries no private content.", systemImage: "exclamationmark.triangle.fill")
                        .font(.footnote)
                }
            }
            .navigationTitle("TrailMesh probe")
            .onAppear { payloadSize = model.selectedPayloadSize }
            .onChange(of: scenePhase) { phase in
                switch phase {
                case .active: model.sceneBecameActive()
                case .background: model.sceneEnteredBackground()
                case .inactive: break
                @unknown default: break
                }
            }
        }
    }
}
