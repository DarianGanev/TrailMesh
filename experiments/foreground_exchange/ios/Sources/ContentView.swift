import SwiftUI

struct ContentView: View {
    @Environment(\.scenePhase) private var scenePhase
    @StateObject private var model = ProbeModel()
    @State private var role: ProbeRole = .sender
    @State private var pairingMode: ProbePairingMode = .roleBased
    @State private var payloadSize = 2048

    private let payloadSizes = [256, 2048, 8192]

    var body: some View {
        NavigationStack {
            Form {
                Section {
                    Text("Test-only transport probe")
                        .font(.title2.weight(.semibold))
                    Text("Both devices start one foreground session. The probe accepts nearby test connections automatically and exchanges generated bytes only. Do not send reports, messages, or private data.")
                        .font(.body)
                }

                Section("This iPhone") {
                    Picker("Role", selection: $role) {
                        ForEach(ProbeRole.allCases) { option in
                            Text(option.title).tag(option)
                        }
                    }
                    Picker("Pairing mode", selection: $pairingMode) {
                        ForEach(ProbePairingMode.allCases) { option in
                            Text(option.title).tag(option)
                        }
                    }
                    Text("Choose the same pairing mode on both phones. In cross-platform mode, this iPhone discovers while Android advertises; the selected sender still controls which phone sends test bytes.")
                        .font(.footnote)
                        .foregroundStyle(.secondary)
                    Picker("Payload size", selection: $payloadSize) {
                        ForEach(payloadSizes, id: \.self) { size in
                            Text(size == 256 ? "256 bytes" : size == 2048 ? "2 KiB (required gate)" : "8 KiB")
                                .tag(size)
                        }
                    }
                    Button("Start test session") {
                        model.start(role: role, payloadSize: payloadSize, pairingMode: pairingMode)
                    }
                    .disabled(model.sessionActive)
                    Button("Stop session", role: .destructive) {
                        model.stop(reason: "Stopped by user.")
                    }
                    .disabled(!model.sessionActive)
                }

                Section("Status") {
                    Text(model.status)
                    Text("\(model.successfulAttempts) successful · \(model.failedAttempts) failed")
                        .monospacedDigit()
                }

                Section("Test log") {
                    if model.logs.isEmpty {
                        Text("No attempts recorded yet.").foregroundStyle(.secondary)
                    } else {
                        ForEach(Array(model.logs.enumerated()), id: \.offset) { item in
                            Text(item.element).font(.caption.monospaced())
                        }
                    }
                    ShareLink("Export redacted log", item: model.exportJSON)
                }

                Section {
                    Label("Automatic verification is intentionally test-only. Google warns that accepting the SDK token without a human comparison does not authenticate the peer. The probe carries no private content.", systemImage: "exclamationmark.triangle.fill")
                        .font(.footnote)
                }
            }
            .navigationTitle("TrailMesh probe")
            .onChange(of: scenePhase) { phase in
                if phase == .background, model.sessionActive {
                    model.stop(reason: "Foreground session stopped when the app left the foreground.")
                }
            }
        }
    }
}
